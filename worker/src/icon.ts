function png(base64: string): Response {
  const bytes = Uint8Array.from(atob(base64), (character) => character.charCodeAt(0));
  return new Response(bytes, {
    headers: {
      'content-type': 'image/png',
      // Immutable in practice: it only changes with a deploy.
      'cache-control': 'public, max-age=31536000, immutable'
    }
  });
}

/**
 * Serve the mark, or null when the path is not one of ours — so the router can
 * fall through without this file knowing about routing.
 */
export function iconResponse(path: string): Response | null {
  if (path === '/icon.png') return png(ICON_DARK);
  if (path === '/icon-light.png') return png(ICON_LIGHT);

  if (path === '/favicon.svg' || path === '/favicon.ico') {
    // The glyph alone, on nothing: a browser tab already has a background, and
    // a tile inside a 16px favicon leaves no room for the anvil.
    const svg =
      '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">' +
      forgeGlyph(64).replace(/^<svg[^>]*>|<\/svg>$/g, '') +
      '</svg>';
    return new Response(svg, {
      headers: {
        'content-type': 'image/svg+xml',
        'cache-control': 'public, max-age=31536000, immutable'
      }
    });
  }

  return null;
}
